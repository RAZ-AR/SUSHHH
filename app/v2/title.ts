// Название своего голоса: человек пишет его перед публикацией, его видят все в центре экрана.
// Чистим то, что может сломать вид или обмануть: управляющие символы, смену направления текста,
// лишние пробелы. Длина — чтобы влезало в две строки над овалом.

export const TITLE_MAX = 60;

// управляющие символы, невидимые разделители и переключатели направления (‮ и т. п.)
// eslint-disable-next-line no-control-regex -- управляющие символы здесь и ищем
const JUNK = /[\u0000-\u001f\u007f-\u009f​-‏‪-‮⁠-⁩﻿]/g;

export function cleanTitle(raw: string) {
  const t = raw.replace(JUNK, " ").replace(/\s+/g, " ").trim();
  return [...t].slice(0, TITLE_MAX).join("").trim(); // по символам, а не по UTF-16: эмодзи не режутся пополам
}
