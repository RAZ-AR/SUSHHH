function pseudonym() {
  try {
    let n = localStorage.getItem("sushhh.name");
    if (!n) localStorage.setItem("sushhh.name", (n = NAMES[Math.floor(Math.random() * NAMES.length)]));
    return n;
  } catch {
    return NAMES[0];
  }
}
